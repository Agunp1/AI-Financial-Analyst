def normalize_name(value: str) -> str:
    return (
        str(value)
        .strip()
        .lower()
        .replace(" ", "_")
        .replace("-", "_")
        .replace("/", "_")
    )


def find_column(
    df: pd.DataFrame,
    candidates: Iterable[str],
    required: bool = True,
) -> str | None:
    lookup = {normalize_name(c): c for c in df.columns}

    for candidate in candidates:
        key = normalize_name(candidate)
        if key in lookup:
            return lookup[key]

    if required:
        raise KeyError(
            "Could not locate required column.\n"
            f"Tried: {list(candidates)}\n"
            f"Available columns: {df.columns.tolist()}"
        )

    return None


def numeric(series: pd.Series, fill_value: float = 0.0) -> pd.Series:
    return pd.to_numeric(series, errors="coerce").fillna(fill_value)


def safe_divide(
    numerator: pd.Series | np.ndarray | float,
    denominator: float,
) -> pd.Series | np.ndarray | float:
    if abs(denominator) <= POLICY.epsilon:
        if isinstance(numerator, pd.Series):
            return pd.Series(0.0, index=numerator.index)
        if isinstance(numerator, np.ndarray):
            return np.zeros_like(numerator, dtype=float)
        return 0.0

    return numerator / denominator


def finite(value: float) -> bool:
    return bool(np.isfinite(value))


def choose_identifier_column(df: pd.DataFrame) -> str:
    return find_column(
        df,
        [
            "symbol",
            "ticker",
            "instrument",
            "security",
            "asset",
            "identifier",
            "name",
        ],
    )


