INPUT_FILE = Path("day64_instrument_exposures.csv")

OUTPUT_ORDERS = Path("day65_exposure_aware_orders.csv")
OUTPUT_TARGETS = Path("day65_target_exposures.csv")
OUTPUT_SUMMARY = Path("day65_portfolio_summary.csv")
OUTPUT_CHECKS = Path("day65_constraint_checks.csv")
OUTPUT_VALIDATION = Path("day65_validation_summary.csv")


@dataclass(frozen=True)
class Policy:
    # Fully funded capital concentration.
    max_capital_weight: float = 0.25

    # Gross economic exposure relative to total capital.
    max_single_instrument_gross_exposure: float = 1.00

    # Risk concentration.
    max_single_instrument_risk_weight: float = 0.35

    # Portfolio-level gross exposure.
    max_portfolio_gross_exposure: float = 2.00

    # Portfolio-level absolute signed notional.
    max_portfolio_absolute_notional: float = 2.00

    # Maximum one-way turnover generated by this layer.
    max_one_way_turnover: float = 0.35

    # Ignore economically tiny trades.
    trade_tolerance: float = 0.001

    # Numerical tolerance.
    epsilon: float = 1e-10


POLICY = Policy()


