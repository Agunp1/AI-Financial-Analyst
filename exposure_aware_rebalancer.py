def build_portfolio_summary(
    original: pd.DataFrame,
    orders: pd.DataFrame,
    capital_base: float,
) -> pd.DataFrame:
    current_gross = float(
        original["gross_exposure_weight"].abs().sum()
    )

    target_gross = float(
        orders["target_gross_exposure_weight"]
        .abs()
        .sum()
    )

    current_net_notional = float(
        original["signed_notional_weight"].sum()
    )

    target_net_notional = float(
        orders["target_signed_notional_weight"].sum()
    )

    current_absolute_notional = float(
        original["signed_notional_weight"].abs().sum()
    )

    target_absolute_notional = float(
        orders["target_signed_notional_weight"]
        .abs()
        .sum()
    )

    current_risk_total = float(
        original["risk_weight"].abs().sum()
    )

    target_risk_total = float(
        orders["target_risk_weight"].abs().sum()
    )

    current_max_capital = float(
        original["capital_weight"].abs().max()
    )

    target_max_capital = float(
        orders["target_capital_weight"].abs().max()
    )

    current_max_risk = float(
        original["risk_weight"].abs().max()
    )

    target_max_risk = float(
        orders["target_risk_weight"].abs().max()
    )

    turnover = calculate_one_way_turnover(orders)

    buy_count = int((orders["action"] == "BUY").sum())
    sell_count = int((orders["action"] == "SELL").sum())
    hold_count = int((orders["action"] == "HOLD").sum())

    summary = pd.DataFrame(
        [
            {
                "capital_base": capital_base,
                "instrument_count": len(orders),
                "current_gross_exposure": current_gross,
                "target_gross_exposure": target_gross,
                "current_net_notional": current_net_notional,
                "target_net_notional": target_net_notional,
                "current_absolute_notional": (
                    current_absolute_notional
                ),
                "target_absolute_notional": (
                    target_absolute_notional
                ),
                "current_total_risk_weight": current_risk_total,
                "target_total_risk_weight": target_risk_total,
                "current_max_capital_weight": current_max_capital,
                "target_max_capital_weight": target_max_capital,
                "current_max_risk_weight": current_max_risk,
                "target_max_risk_weight": target_max_risk,
                "one_way_turnover": turnover,
                "buy_count": buy_count,
                "sell_count": sell_count,
                "hold_count": hold_count,
            }
        ]
    )

    return summary


