def build_orders(
    targets: pd.DataFrame,
    capital_base: float,
) -> pd.DataFrame:
    result = targets.copy()

    result["current_capital_dollars"] = (
        result["capital_weight"] * capital_base
    )

    result["target_capital_dollars"] = (
        result["target_capital_weight"] * capital_base
    )

    result["capital_trade_dollars"] = (
        result["target_capital_dollars"]
        - result["current_capital_dollars"]
    )

    result["capital_trade_weight"] = (
        result["target_capital_weight"]
        - result["capital_weight"]
    )

    result["gross_exposure_change"] = (
        result["target_gross_exposure_weight"]
        - result["gross_exposure_weight"]
    )

    result["signed_notional_change"] = (
        result["target_signed_notional_weight"]
        - result["signed_notional_weight"]
    )

    result["risk_weight_change"] = (
        result["target_risk_weight"]
        - result["risk_weight"]
    )

    def classify_action(row: pd.Series) -> str:
        changes = [
            abs(float(row["capital_trade_weight"])),
            abs(float(row["gross_exposure_change"])),
            abs(float(row["signed_notional_change"])),
            abs(float(row["risk_weight_change"])),
        ]

        if max(changes) <= POLICY.trade_tolerance:
            return "HOLD"

        # Direction is based primarily on economic/notional exposure.
        if row["signed_notional_change"] > POLICY.trade_tolerance:
            return "BUY"

        if row["signed_notional_change"] < -POLICY.trade_tolerance:
            return "SELL"

        if row["capital_trade_weight"] > POLICY.trade_tolerance:
            return "BUY"

        if row["capital_trade_weight"] < -POLICY.trade_tolerance:
            return "SELL"

        return "HOLD"

    result["action"] = result.apply(
        classify_action,
        axis=1,
    )

    return result


