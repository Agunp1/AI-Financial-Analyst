def estimate_capital_base(df: pd.DataFrame) -> float:
    """
    Recover the portfolio capital base from Day 64 capital exposure/weights.

    Multiple observations are used and the median is taken for robustness.
    """

    valid = (
        np.isfinite(df["capital_exposure"])
        & np.isfinite(df["capital_weight"])
        & (df["capital_weight"].abs() > POLICY.epsilon)
    )

    estimates = (
        df.loc[valid, "capital_exposure"]
        / df.loc[valid, "capital_weight"]
    ).abs()

    estimates = estimates[
        np.isfinite(estimates)
        & (estimates > POLICY.epsilon)
    ]

    if estimates.empty:
        raise ValueError(
            "Unable to infer portfolio capital base from Day 64."
        )

    capital_base = float(estimates.median())

    if not finite(capital_base) or capital_base <= 0:
        raise ValueError("Invalid inferred capital base.")

    return capital_base


