def determine_applicable_capital_limit(
    row: pd.Series,
) -> float:
    """
    Apply the capital concentration limit only to economically funded capital.

    Derivatives can have low capital_factor but high notional exposure, so their
    notional and risk constraints are handled independently.
    """

    capital_factor = abs(float(row["capital_factor"]))

    if capital_factor >= 0.75:
        return POLICY.max_capital_weight

    return np.inf


def build_initial_targets(df: pd.DataFrame) -> pd.DataFrame:
    """
    Begin from Day 64 exposures.

    This layer is deliberately conservative: it does not invent alpha signals.
    It keeps existing exposure unless a risk/concentration constraint requires
    scaling.
    """

    result = df.copy()

    result["target_capital_weight"] = result["capital_weight"].copy()

    result["target_gross_exposure_weight"] = (
        result["gross_exposure_weight"].copy()
    )

    result["target_signed_notional_weight"] = (
        result["signed_notional_weight"].copy()
    )

    result["target_risk_weight"] = result["risk_weight"].copy()

    result["scale_factor"] = 1.0
    result["constraint_reason"] = "UNCHANGED"

    return result


def instrument_scale_factor(row: pd.Series) -> tuple[float, list[str]]:
    scale = 1.0
    reasons: list[str] = []

    capital_limit = determine_applicable_capital_limit(row)

    capital_weight = abs(float(row["capital_weight"]))
    gross_weight = abs(float(row["gross_exposure_weight"]))
    risk_weight = abs(float(row["risk_weight"]))

    if (
        np.isfinite(capital_limit)
        and capital_weight > capital_limit + POLICY.epsilon
    ):
        scale = min(
            scale,
            capital_limit / capital_weight,
        )
        reasons.append("CAPITAL_CONCENTRATION")

    if (
        gross_weight
        > POLICY.max_single_instrument_gross_exposure
        + POLICY.epsilon
    ):
        scale = min(
            scale,
            POLICY.max_single_instrument_gross_exposure
            / gross_weight,
        )
        reasons.append("GROSS_EXPOSURE_CONCENTRATION")

    if (
        risk_weight
        > POLICY.max_single_instrument_risk_weight
        + POLICY.epsilon
    ):
        scale = min(
            scale,
            POLICY.max_single_instrument_risk_weight
            / risk_weight,
        )
        reasons.append("RISK_CONCENTRATION")

    scale = float(np.clip(scale, 0.0, 1.0))

    return scale, reasons


def apply_instrument_constraints(
    targets: pd.DataFrame,
) -> pd.DataFrame:
    result = targets.copy()

    for idx, row in result.iterrows():
        scale, reasons = instrument_scale_factor(row)

        result.at[idx, "scale_factor"] = scale

        if reasons:
            result.at[idx, "constraint_reason"] = "|".join(reasons)

        result.at[idx, "target_capital_weight"] = (
            row["capital_weight"] * scale
        )

        result.at[idx, "target_gross_exposure_weight"] = (
            row["gross_exposure_weight"] * scale
        )

        result.at[idx, "target_signed_notional_weight"] = (
            row["signed_notional_weight"] * scale
        )

        result.at[idx, "target_risk_weight"] = (
            row["risk_weight"] * scale
        )

    return result


def apply_portfolio_gross_limit(
    targets: pd.DataFrame,
) -> pd.DataFrame:
    result = targets.copy()

    gross_total = float(
        result["target_gross_exposure_weight"].abs().sum()
    )

    if (
        gross_total
        <= POLICY.max_portfolio_gross_exposure
        + POLICY.epsilon
    ):
        return result

    portfolio_scale = (
        POLICY.max_portfolio_gross_exposure / gross_total
    )

    exposure_columns = [
        "target_capital_weight",
        "target_gross_exposure_weight",
        "target_signed_notional_weight",
        "target_risk_weight",
    ]

    result[exposure_columns] = (
        result[exposure_columns] * portfolio_scale
    )

    result["scale_factor"] = (
        result["scale_factor"] * portfolio_scale
    )

    result["constraint_reason"] = np.where(
        result["constraint_reason"].eq("UNCHANGED"),
        "PORTFOLIO_GROSS_LIMIT",
        result["constraint_reason"]
        + "|PORTFOLIO_GROSS_LIMIT",
    )

    return result


def apply_portfolio_notional_limit(
    targets: pd.DataFrame,
) -> pd.DataFrame:
    result = targets.copy()

    absolute_notional = float(
        result["target_signed_notional_weight"].abs().sum()
    )

    if (
        absolute_notional
        <= POLICY.max_portfolio_absolute_notional
        + POLICY.epsilon
    ):
        return result

    portfolio_scale = (
        POLICY.max_portfolio_absolute_notional
        / absolute_notional
    )

    exposure_columns = [
        "target_capital_weight",
        "target_gross_exposure_weight",
        "target_signed_notional_weight",
        "target_risk_weight",
    ]

    result[exposure_columns] = (
        result[exposure_columns] * portfolio_scale
    )

    result["scale_factor"] = (
        result["scale_factor"] * portfolio_scale
    )

    result["constraint_reason"] = np.where(
        result["constraint_reason"].eq("UNCHANGED"),
        "PORTFOLIO_NOTIONAL_LIMIT",
        result["constraint_reason"]
        + "|PORTFOLIO_NOTIONAL_LIMIT",
    )

    return result


