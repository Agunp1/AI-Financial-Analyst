def build_constraint_checks(
    orders: pd.DataFrame,
) -> pd.DataFrame:
    rows: list[dict] = []

    # --------------------------------------------------------------
    # Fully funded capital concentration
    # --------------------------------------------------------------

    funded = orders[
        orders["capital_factor"].abs() >= 0.75
    ].copy()

    largest_funded_capital = (
        float(funded["target_capital_weight"].abs().max())
        if not funded.empty
        else 0.0
    )

    rows.append(
        {
            "check": "Fully funded capital concentration",
            "passed": (
                largest_funded_capital
                <= POLICY.max_capital_weight
                + POLICY.epsilon
            ),
            "value": largest_funded_capital,
            "limit": POLICY.max_capital_weight,
            "details": (
                f"Largest applicable target capital weight: "
                f"{largest_funded_capital:.4%}; "
                f"limit: {POLICY.max_capital_weight:.4%}"
            ),
        }
    )

    # --------------------------------------------------------------
    # Single instrument gross exposure
    # --------------------------------------------------------------

    max_gross = float(
        orders["target_gross_exposure_weight"]
        .abs()
        .max()
    )

    rows.append(
        {
            "check": "Single instrument gross exposure",
            "passed": (
                max_gross
                <= POLICY.max_single_instrument_gross_exposure
                + POLICY.epsilon
            ),
            "value": max_gross,
            "limit": POLICY.max_single_instrument_gross_exposure,
            "details": (
                f"Largest instrument gross exposure weight: "
                f"{max_gross:.4%}"
            ),
        }
    )

    # --------------------------------------------------------------
    # Single instrument risk concentration
    # --------------------------------------------------------------

    max_risk = float(
        orders["target_risk_weight"].abs().max()
    )

    rows.append(
        {
            "check": "Single instrument risk concentration",
            "passed": (
                max_risk
                <= POLICY.max_single_instrument_risk_weight
                + POLICY.epsilon
            ),
            "value": max_risk,
            "limit": POLICY.max_single_instrument_risk_weight,
            "details": (
                f"Largest instrument target risk weight: "
                f"{max_risk:.4%}"
            ),
        }
    )

    # --------------------------------------------------------------
    # Portfolio gross exposure
    # --------------------------------------------------------------

    portfolio_gross = float(
        orders["target_gross_exposure_weight"]
        .abs()
        .sum()
    )

    rows.append(
        {
            "check": "Portfolio gross exposure",
            "passed": (
                portfolio_gross
                <= POLICY.max_portfolio_gross_exposure
                + POLICY.epsilon
            ),
            "value": portfolio_gross,
            "limit": POLICY.max_portfolio_gross_exposure,
            "details": (
                f"Target portfolio gross exposure: "
                f"{portfolio_gross:.4f}x capital"
            ),
        }
    )

    # --------------------------------------------------------------
    # Absolute signed notional
    # --------------------------------------------------------------

    absolute_notional = float(
        orders["target_signed_notional_weight"]
        .abs()
        .sum()
    )

    rows.append(
        {
            "check": "Portfolio absolute notional exposure",
            "passed": (
                absolute_notional
                <= POLICY.max_portfolio_absolute_notional
                + POLICY.epsilon
            ),
            "value": absolute_notional,
            "limit": POLICY.max_portfolio_absolute_notional,
            "details": (
                f"Absolute target signed notional: "
                f"{absolute_notional:.4f}x capital"
            ),
        }
    )

    # --------------------------------------------------------------
    # Turnover
    # --------------------------------------------------------------

    turnover = calculate_one_way_turnover(orders)

    rows.append(
        {
            "check": "One-way turnover",
            "passed": (
                turnover
                <= POLICY.max_one_way_turnover
                + POLICY.epsilon
            ),
            "value": turnover,
            "limit": POLICY.max_one_way_turnover,
            "details": (
                f"One-way turnover: {turnover:.4%}; "
                f"limit: {POLICY.max_one_way_turnover:.4%}"
            ),
        }
    )

    # --------------------------------------------------------------
    # Valid actions
    # --------------------------------------------------------------

    allowed_actions = {"BUY", "SELL", "HOLD"}

    actions_valid = bool(
        orders["action"].isin(allowed_actions).all()
    )

    rows.append(
        {
            "check": "Valid rebalance actions",
            "passed": actions_valid,
            "value": float(actions_valid),
            "limit": 1.0,
            "details": "Allowed actions: BUY, SELL, HOLD",
        }
    )

    # --------------------------------------------------------------
    # Finite output
    # --------------------------------------------------------------

    numeric_columns = [
        "target_capital_weight",
        "target_gross_exposure_weight",
        "target_signed_notional_weight",
        "target_risk_weight",
        "capital_trade_weight",
        "risk_weight_change",
    ]

    finite_outputs = bool(
        np.isfinite(
            orders[numeric_columns].to_numpy(dtype=float)
        ).all()
    )

    rows.append(
        {
            "check": "Finite exposure-aware outputs",
            "passed": finite_outputs,
            "value": float(finite_outputs),
            "limit": 1.0,
            "details": (
                "Target exposure and rebalance fields "
                "must contain finite values."
            ),
        }
    )

    return pd.DataFrame(rows)


