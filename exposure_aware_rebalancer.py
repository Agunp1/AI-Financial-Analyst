def load_day64() -> pd.DataFrame:
    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Required input not found: {INPUT_FILE}"
        )

    raw = pd.read_csv(INPUT_FILE)

    if raw.empty:
        raise ValueError("Day 64 instrument exposure file is empty.")

    symbol_col = choose_identifier_column(raw)

    asset_class_col = find_column(raw, ["asset_class"])
    instrument_type_col = find_column(raw, ["instrument_type"])

    quantity_col = find_column(raw, ["quantity"])
    price_col = find_column(raw, ["price"])
    multiplier_col = find_column(raw, ["contract_multiplier"])

    market_value_col = find_column(raw, ["market_value"])
    current_weight_col = find_column(raw, ["current_weight"])

    capital_factor_col = find_column(raw, ["capital_factor"])
    notional_factor_col = find_column(raw, ["notional_factor"])
    risk_multiplier_col = find_column(raw, ["risk_multiplier"])

    capital_exposure_col = find_column(raw, ["capital_exposure"])
    signed_notional_col = find_column(raw, ["signed_notional_exposure"])
    gross_notional_col = find_column(raw, ["gross_notional_exposure"])
    risk_exposure_col = find_column(raw, ["risk_exposure"])

    capital_weight_col = find_column(raw, ["capital_weight"])
    gross_weight_col = find_column(raw, ["gross_exposure_weight"])
    signed_notional_weight_col = find_column(
        raw,
        ["signed_notional_weight"],
    )
    risk_weight_col = find_column(raw, ["risk_weight"])
    notional_weight_col = find_column(raw, ["notional_weight"])

    df = pd.DataFrame(
        {
            "symbol": raw[symbol_col].astype(str),
            "asset_class": raw[asset_class_col].astype(str),
            "instrument_type": raw[instrument_type_col].astype(str),
            "quantity": numeric(raw[quantity_col]),
            "price": numeric(raw[price_col]),
            "contract_multiplier": numeric(raw[multiplier_col]),
            "market_value": numeric(raw[market_value_col]),
            "day64_current_weight": numeric(raw[current_weight_col]),
            "capital_factor": numeric(raw[capital_factor_col]),
            "notional_factor": numeric(raw[notional_factor_col]),
            "risk_multiplier": numeric(raw[risk_multiplier_col]),
            "capital_exposure": numeric(raw[capital_exposure_col]),
            "signed_notional_exposure": numeric(raw[signed_notional_col]),
            "gross_notional_exposure": numeric(raw[gross_notional_col]),
            "risk_exposure": numeric(raw[risk_exposure_col]),
            "capital_weight": numeric(raw[capital_weight_col]),
            "gross_exposure_weight": numeric(raw[gross_weight_col]),
            "signed_notional_weight": numeric(
                raw[signed_notional_weight_col]
            ),
            "risk_weight": numeric(raw[risk_weight_col]),
            "notional_weight": numeric(raw[notional_weight_col]),
        }
    )

    if df["symbol"].duplicated().any():
        duplicates = df.loc[
            df["symbol"].duplicated(keep=False),
            "symbol",
        ].tolist()

        raise ValueError(
            "Duplicate instrument identifiers found: "
            f"{duplicates}"
        )

    return df


