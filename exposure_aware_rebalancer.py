def build_validation_summary(
    original: pd.DataFrame,
    orders: pd.DataFrame,
    checks: pd.DataFrame,
    summary: pd.DataFrame,
) -> pd.DataFrame:
    rows: list[dict] = []

    def add(
        check: str,
        passed: bool,
        details: str,
    ) -> None:
        rows.append(
            {
                "check": check,
                "passed": bool(passed),
                "details": details,
            }
        )

    add(
        "Day 64 input loaded",
        len(original) > 0,
        f"Rows: {len(original)}",
    )

    add(
        "Exposure-aware targets generated",
        len(orders) == len(original),
        (
            f"Input instruments: {len(original)}; "
            f"output instruments: {len(orders)}"
        ),
    )

    add(
        "Unique instrument identifiers",
        not orders["symbol"].duplicated().any(),
        f"Unique symbols: {orders['symbol'].nunique()}",
    )

    add(
        "All actions valid",
        orders["action"].isin(
            {"BUY", "SELL", "HOLD"}
        ).all(),
        "Allowed actions: BUY, SELL, HOLD",
    )

    add(
        "Constraint diagnostics generated",
        not checks.empty,
        f"Checks: {len(checks)}",
    )

    add(
        "All exposure constraints passed",
        bool(checks["passed"].all()),
        (
            f"Passed: {int(checks['passed'].sum())}/"
            f"{len(checks)}"
        ),
    )

    add(
        "Portfolio summary generated",
        len(summary) == 1,
        f"Rows: {len(summary)}",
    )

    exposure_cols = [
        "target_capital_weight",
        "target_gross_exposure_weight",
        "target_signed_notional_weight",
        "target_risk_weight",
    ]

    add(
        "Target exposures contain finite values",
        np.isfinite(
            orders[exposure_cols].to_numpy(dtype=float)
        ).all(),
        "Capital, gross, notional and risk targets checked.",
    )

    add(
        "Turnover within policy",
        calculate_one_way_turnover(orders)
        <= POLICY.max_one_way_turnover + POLICY.epsilon,
        (
            f"Turnover: "
            f"{calculate_one_way_turnover(orders):.4%}; "
            f"limit: {POLICY.max_one_way_turnover:.4%}"
        ),
    )

    # Critical derivative-aware validation:
    derivative_mask = (
        orders["capital_factor"].abs()
        < orders["notional_factor"].abs()
    )

    derivative_separation_exists = True

    if derivative_mask.any():
        derivative_separation_exists = bool(
            (
                orders.loc[
                    derivative_mask,
                    "gross_notional_exposure",
                ].abs()
                >=
                orders.loc[
                    derivative_mask,
                    "capital_exposure",
                ].abs()
            ).all()
        )

    add(
        "Derivative capital and notional remain separated",
        derivative_separation_exists,
        (
            "Derivative-like positions retain distinct "
            "capital and notional treatment."
        ),
    )

    validation = pd.DataFrame(rows)

    validation["passed_tests"] = int(
        validation["passed"].sum()
    )

    validation["total_tests"] = len(validation)

    validation["pass_rate"] = (
        validation["passed_tests"]
        / validation["total_tests"]
    )

    return validation


