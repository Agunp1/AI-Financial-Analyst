"""
Vittantra - Exposure-Aware Portfolio Rebalancer

Purpose
-------
Build a portfolio rebalancing layer on top of the Day 64 exposure engine.

This module deliberately separates:

1. Capital allocation
2. Gross notional exposure
3. Signed notional exposure
4. Risk exposure

This is especially important for derivatives, where notional exposure should
not automatically be interpreted as fully funded capital.

Inputs
------
day64_instrument_exposures.csv

Outputs
-------
day65_exposure_aware_orders.csv
day65_target_exposures.csv
day65_portfolio_summary.csv
day65_constraint_checks.csv
day65_validation_summary.csv

Important
---------
This is a research and portfolio-risk framework. Proposed rebalances are
analytical outputs, not automatic trade instructions.
"""

