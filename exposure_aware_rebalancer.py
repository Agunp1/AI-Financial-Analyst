# TURNOVER CONTROL
# ======================================================================

def calculate_one_way_turnover(
    orders: pd.DataFrame,
) -> float:
    """
    One-way turnover is half of total absolute capital-weight change.
    """

    return float(
        0.5
        * orders["capital_trade_weight"].abs().sum()
    )


def apply_turnover_limit(
    original: pd.DataFrame,
    targets: pd.DataFrame,
) -> pd.DataFrame:
    result = targets.copy()

    capital_changes = (
        result["target_capital_weight"]
        - original["capital_weight"]
    )

    turnover = float(
        0.5 * capital_changes.abs().sum()
    )

    if turnover <= POLICY.max_one_way_turnover + POLICY.epsilon:
        return result

    scale = POLICY.max_one_way_turnover / turnover

    mappings = [
        ("capital_weight", "target_capital_weight"),
        (
            "gross_exposure_weight",
            "target_gross_exposure_weight",
        ),
        (
            "signed_notional_weight",
            "target_signed_notional_weight",
        ),
        ("risk_weight", "target_risk_weight"),
    ]

    for current_col, target_col in mappings:
        result[target_col] = (
            original[current_col]
            + scale
            * (
                result[target_col]
                - original[current_col]
            )
        )

    result["constraint_reason"] = np.where(
        result["constraint_reason"].eq("UNCHANGED"),
        "TURNOVER_LIMIT",
        result["constraint_reason"] + "|TURNOVER_LIMIT",
    )

    return result


